
function forLoop() {
    // 1 - 20 print
    for (let num = 1; num <= 10; num++) {
        console.log(num);
    }
}

// forLoop();

function whileLoop() {
    let num = 1;
    while (num <= 10) {
        console.log(num);
        num++;
    }
}

// whileLoop();


function doWhileLoop() {
    let num = 1;
    do {
        console.log(num);
        num++;
    }
    while (num <= 10);
}

